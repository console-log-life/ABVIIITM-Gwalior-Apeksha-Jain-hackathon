"""Per-document latency of the full NLP pipeline (clean -> entities -> FinBERT -> events -> corroboration ->
impact) on THIS machine, using real cached documents. Prints median / p95 and writes
data/eval/benchmark_results.json + docs/benchmark.md.

Usage:  python src/scripts/benchmark_latency.py [--n 200] [--batch 32]
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import statistics
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import torch  # noqa: E402

from app.config import Settings, get_settings  # noqa: E402
from risk_engine.impact_scoring.corroboration import CorroborationTracker  # noqa: E402
from risk_engine.impact_scoring.scorer import ImpactScorer  # noqa: E402
from risk_engine.ingestion.replay import load_cached_documents  # noqa: E402
from risk_engine.pipeline import DocumentRejected, RiskPipeline  # noqa: E402
from risk_engine.sentiment.finbert import SentimentEngine  # noqa: E402

OUT_JSON = ROOT / "data" / "eval" / "benchmark_results.json"
OUT_MD = ROOT / "docs" / "benchmark.md"


def pct(values: list[float], q: float) -> float:
    v = sorted(values)
    k = (len(v) - 1) * q
    lo, hi = int(k), min(int(k) + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (k - lo)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--out-dir", default=None, help="write benchmark_results.json + benchmark.md here instead of "
                                                    "data/eval/ and docs/ (verification runs)")
    ap.add_argument("--batch", type=int, default=32)
    args = ap.parse_args()

    docs = load_cached_documents(get_settings().cache_path)
    docs = docs[-args.n:]
    t0 = time.perf_counter()
    pipe = RiskPipeline(sentiment=SentimentEngine(Settings(sentiment_backend="finbert")), scorer=ImpactScorer(),
                        corroboration=CorroborationTracker(6))
    load_s = time.perf_counter() - t0
    for d in docs[:5]:  # warm-up
        try:
            pipe.process(d)
        except DocumentRejected:
            pass

    single: list[float] = []
    for d in docs:
        t = time.perf_counter()
        try:
            pipe.process(d)
        except DocumentRejected:
            continue
        single.append((time.perf_counter() - t) * 1000)

    t = time.perf_counter()
    for i in range(0, len(docs), args.batch):
        pipe.process_batch(docs[i : i + args.batch], skip_rejected=True)
    batch_ms_per_doc = (time.perf_counter() - t) * 1000 / len(docs)

    res = {
        "generated_at": datetime.now(UTC).isoformat(), "n_documents": len(single),
        "source": "most recent CACHED_REAL documents (real headlines/posts)",
        "per_document_ms": {"median": round(statistics.median(single), 1), "p95": round(pct(single, 0.95), 1),
                            "mean": round(statistics.mean(single), 1), "max": round(max(single), 1)},
        "batched_ms_per_document": round(batch_ms_per_doc, 1), "batch_size": args.batch,
        "model_load_s": round(load_s, 1),
        "machine": {"platform": platform.platform(), "processor": platform.processor(), "cpu_count": os.cpu_count(),
                    "torch_threads": torch.get_num_threads(), "python": platform.python_version(), "gpu": False},
    }
    out_json, out_md = OUT_JSON, OUT_MD
    if args.out_dir:
        Path(args.out_dir).mkdir(parents=True, exist_ok=True)
        out_json, out_md = Path(args.out_dir) / OUT_JSON.name, Path(args.out_dir) / OUT_MD.name
    out_json.write_text(json.dumps(res, indent=2), encoding="utf-8")
    p = res["per_document_ms"]
    out_md.write_text(
        "# Latency benchmark\n\n"
        f"Generated by `src/scripts/benchmark_latency.py` at {res['generated_at']} on the developer laptop "
        f"({res['machine']['platform']}, {res['machine']['cpu_count']} logical CPUs, CPU-only torch, "
        f"{res['machine']['torch_threads']} threads).\n\n"
        f"Full pipeline per document (clean → entities → FinBERT → events → corroboration → impact), "
        f"n = {res['n_documents']} real cached documents, one document per call:\n\n"
        "| Metric | ms |\n|---|---:|\n"
        f"| median | {p['median']} |\n| p95 | {p['p95']} |\n| mean | {p['mean']} |\n| max | {p['max']} |\n"
        f"| batched ({args.batch} docs/call), per document | {res['batched_ms_per_document']} |\n\n"
        f"Model load (FinBERT + spaCy, from local cache): {res['model_load_s']} s.\n"
        "Numbers depend on the machine and on text length (social posts are longer than headlines).\n",
        encoding="utf-8")
    print(f"n={res['n_documents']}  median {p['median']} ms  p95 {p['p95']} ms  mean {p['mean']} ms  "
          f"batched {res['batched_ms_per_document']} ms/doc  (model load {res['model_load_s']} s)")
    print(f"wrote {out_json}, {out_md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
